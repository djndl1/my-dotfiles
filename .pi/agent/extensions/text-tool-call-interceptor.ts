/**
 * Text Tool Call Interceptor Extension
 *
 * Detects tool calls written as plain text inside assistant message content
 * (e.g. <bash><param=command>...</param></bash>). On user confirmation, executes
 * bash commands via pi.exec() and feeds the result back as a message entry.
 */

import type { ExtensionAPI } from "@earendil-works/pi-coding-agent";

// Matches <tool-name>...</tool-name> blocks with param children
const BLOCK_RE = /<([A-Za-z_][\w\-]*)>([\s\S]*?)<\/\1>/g;
// Matches <param=name>value</param> inside a block (value must not be just "...")
const PARAM_RE = /<param=([\w\-]+)>([\s\S]*?)<\/param>/g;

const OUR_CUSTOM_TYPES = new Set([
  "text-tool-call-result",
  "text-tool-call-error",
  "text-tool-call-approved",
  "text-tool-call-blocked",
]);

interface PendingCall {
  toolName: string;
  args: Record<string, string>;
  raw: string;
}

export default function (pi: ExtensionAPI) {
  // messageEntryId -> detected fake tool calls from that assistant message
  const pending = new Map<string, PendingCall[]>();

  // 1. Scan every assistant message for text-formatted tool calls
  pi.on("message_end", (_event: any, _ctx: any) => {
    const { message } = _event;
    if (message.role !== "assistant") return;

    // Skip messages generated by this extension to avoid re-scanning our own output
    if (message.customType && OUR_CUSTOM_TYPES.has(message.customType)) return;

    const text = message.content
      .filter((c: any) => c.type === "text")
      .map((c: any) => c.text)
      .join("\n");

    const calls: PendingCall[] = [];
    let match: RegExpExecArray | null;
    while ((match = BLOCK_RE.exec(text)) !== null) {
      const toolName = match[1];
      const paramsBlock = match[2];
      const args: Record<string, string> = {};
      let pMatch: RegExpExecArray | null;
      while ((pMatch = PARAM_RE.exec(paramsBlock)) !== null) {
        const val = pMatch[2].trim();
        // Ignore placeholder values like "..." from truncated display text
        if (val === "...") continue;
        args[pMatch[1]] = val;
      }
      // Only register if we actually found usable params
      if (Object.keys(args).length > 0) {
        calls.push({ toolName, args, raw: match[0] });
      }
    }

    if (calls.length > 0) {
      pending.set(message.id, calls);
    }
  });

  // 2. At turn end, ask the user about each detected call
  pi.on("turn_end", async (event: any, ctx: any) => {
    const { message, entries } = event;
    if (!message || message.role !== "assistant") return;

    const calls = pending.get(message.id);
    if (!calls || calls.length === 0) return;

    const newEntries = [...entries];
    let anyPresented = false;

    for (const call of calls) {
      const argsStr = Object.entries(call.args)
        .map(([k, v]) => `${k}: ${JSON.stringify(v)}`)
        .join(", ");

      const confirmed = await ctx.ui.confirm(
        "Execute text tool call?",
        "Found in assistant message (not a structured tool_calls entry):\n\n" +
          `${call.toolName}(${argsStr})\n\n` +
          `Raw:\n${call.raw.slice(0, 400)}${call.raw.length > 400 ? "..." : ""}`,
      );

      if (confirmed) {
        // Try to execute bash commands via pi.exec()
        if (call.toolName === "bash" && call.args.command) {
          try {
            const result = await pi.exec("sh", ["-c", call.args.command]);
            const stdout = result.stdout?.trim() || "";
            const stderr = result.stderr?.trim() || "";
            const exitCode = typeof result.exitCode === "number" ? result.exitCode : undefined;

            const lines = [
              `$ ${call.args.command}`,
              exitCode !== undefined ? `exit code: ${exitCode}` : "",
              stdout,
              stderr,
            ].filter(Boolean);

            newEntries.push({
              type: "custom_message",
              customType: "text-tool-call-result",
              content:
                `Executed text tool call: ${call.toolName}(${argsStr})\n\n` +
                `Result:\n\`\`\`\n${lines.join("\n")}\n\`\`\``,
              display: true,
            });
            ctx.ui.notify(`Executed: ${call.toolName}`, "info");
          } catch (err: any) {
            newEntries.push({
              type: "custom_message",
              customType: "text-tool-call-error",
              content:
                `Failed to execute text tool call: ${call.toolName}(${argsStr})\n\n` +
                `Error: ${err?.message ?? String(err)}\n\n` +
                `Raw block:\n\`\`\`\n${call.raw}\n\`\`\``,
              display: true,
            });
            ctx.ui.notify(`Error: ${call.toolName}`, "error");
          }
        } else {
          // Non-bash tool: tell user to run manually
          newEntries.push({
            type: "custom_message",
            customType: "text-tool-call-approved",
            content:
              `User approved text tool call: ${call.toolName}(${argsStr})\n\n` +
              `Execute this command yourself and paste the result back.\n\n` +
              `Raw block:\n\`\`\`\n${call.raw}\n\`\`\``,
            display: true,
          });
          ctx.ui.notify(`Approved: ${call.toolName}`, "info");
        }
      } else {
        newEntries.push({
          type: "custom_message",
          customType: "text-tool-call-blocked",
          content:
            `User blocked text tool call: ${call.toolName}(${argsStr})\n\n` +
            `Raw block:\n\`\`\`\n${call.raw}\n\`\`\``,
          display: true,
        });
        ctx.ui.notify(`Blocked: ${call.toolName}`, "warning");
      }
      anyPresented = true;
    }

    pending.delete(message.id);

    if (anyPresented && newEntries.length > entries.length) {
      return { entries: newEntries, continue: true };
    }
  });
}
